async function main() {
  console.log('Mulai seed soal ujian...');

  // Hapus soal lama (opsional - uncomment jika ingin replace)
  // await prisma.soal.deleteMany();

  let count = 0;
  for (const soal of soalData) {
    const existing = await prisma.soal.findFirst({
      where: {
        pertanyaan: soal.pertanyaan,
        mataPelajaran: soal.mataPelajaran,
      },
    });

    if (!existing) {
      await prisma.soal.create({ data: soal });
      count++;
    }
  }

  const total = await prisma.soal.count();
  console.log(`Seed selesai! ${count} soal baru ditambahkan. Total soal: ${total}`);

  // Tampilkan ringkasan per mata pelajaran
  const tik = await prisma.soal.count({ where: { mataPelajaran: 'TIK' } });
  const mat = await prisma.soal.count({ where: { mataPelajaran: 'Matematika' } });
  const bindo = await prisma.soal.count({ where: { mataPelajaran: 'Bahasa Indonesia' } });
  const pu = await prisma.soal.count({ where: { mataPelajaran: 'Pengetahuan Umum' } });
  console.log(`\nRingkasan:`);
  console.log(`  TIK: ${tik} soal`);
  console.log(`  Matematika: ${mat} soal`);
  console.log(`  Bahasa Indonesia: ${bindo} soal`);
  console.log(`  Pengetahuan Umum: ${pu} soal`);
}

